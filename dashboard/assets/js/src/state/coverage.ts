/**
 * state/coverage.ts — periodic-table coverage state + live classifier
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * Owns the answer to "which of the 90 essentials does the active regimen
 * cover, and how heavily." Builds a typed CoverageSnapshot keyed by the
 * canonical essential name — the single source of the live numbers consumed by
 * views/coverage.ts (hero count + per-section counts + per-tile status). The
 * layout (coverage-layout-data.json) joins to this snapshot via each tile's
 * `key` field, which equals the essential `name` here.
 *
 * DATA SOURCE:
 *   The essentials come from `essentials-targets-data.json` — the Wallach
 *   targets DB GENERATED by eden/tools/targets_derive.py from the sealed
 *   pillars (numeric targets are Wallach dose claims). Inlined at build
 *   via esbuild JSON import + validated through Zod at the boundary. Each entry
 *   carries its canon `slug` — the join key to the registry resolver below.
 *
 * LIVE CLASSIFIER:
 *   The math lives here — the page loads one bundle and no other script. Every NUMBER
 *   still comes from the sealed pillars (target.low/unit from the targets DB; nutrient
 *   amounts from regimen item labels). Nothing is invented; §00.A holds.
 *
 *   IDENTITY: which essential a label nutrient credits is
 *   resolved by the ONE registry resolver — core/nutrient-resolver.ts::resolveSlug,
 *   a faithful port of eden/tools/nutrient_resolve.py, proven equal by the
 *   nutrient_resolver_parity invariant + a vitest. It returns a canon slug; each
 *   target carries its slug, so the join is a direct slug key (no display-name
 *   string-matching). This replaced a hand-rolled matcher that disagreed with the
 *   registry (e.g. it silently dropped "Thiamin" → Vitamin B1).
 *
 *   UNITS: mcg/mg unify into one mg-family. The A/D/E targets are METRIC (mcg RAE / mcg /
 *   mg) so they line up with Youngevity's product units. RESIDUAL: no target is IU-family
 *   anymore, so a product that still lists A/D/E in IU lands in the (now unused) totalIU
 *   accumulator and does NOT count toward its metric target — 7 products today. Closeable
 *   by converting per-vitamin IU→mcg in toMg (needs the nutrient identity). Full
 *   canonical-unit unification is not done.
 *
 *   Pipeline: collect the active regimen (the single-writer slot state — committed +
 *   manual items, minus removed, with override scaling) → resolve each label
 *   nutrient to a canon slug + sum into the target's per-essential mg/IU totals
 *   (unit-convert + scale) → classify each essential against its Wallach target.
 *   The 34 trace_pdm plant-derived minerals have no per-mineral dose; they share ONE graduated
 *   verdict from the plant-derived-mineral aggregate (Σ vehicle mg / the 924 mg
 *   goal — pdm-coverage-data.json), computed once per recompute (pdmAggregate).
 *
 *   Numeric thresholds: covered ≥ 0.95·low, partial ≥ 0.30·low, else gap. ONE deliberate
 *   §00.A rule sits on top: a numeric target with low ≤ 0 and zero delivery reports ''
 *   (pending), never 'covered' — marking a tile covered with nothing delivered would be an
 *   overclaim.
 *
 *   Status buckets: the numeric verdicts above; a dietary target reads covered once any
 *   source supplies it; anything with no target at all reads '' (pending, rendered grey).
 *   Empty regimen ⇒ numeric targets are `gap`, the rest pending — the truthful
 *   bare state. recompute() re-runs on every `regimen:changed`.
 * ═══════════════════════════════════════════════════════════════════════════
 */

