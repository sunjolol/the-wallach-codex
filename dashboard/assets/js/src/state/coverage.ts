interface PdmDelivery {
  totalMg: number;
  present: boolean;
  sources: string[];
}

/**
 * Aggregate plant-derived-mineral delivery across the effective regimen: sum each
 * item's vehicle mg (serving-scaled), OR-ing the present-but-unquantified flag.
 * Matched by canonical name (the same join the auto-heal uses). This ONE aggregate
 * scores all 33 trace_pdm tiles (they have no per-mineral delivery of their own).
 */
function pdmAggregate(items: RegimenItem[], overrides: OverridesMap): PdmDelivery {
  const map = pdmByName();
  let totalMg = 0;
  let present = false;
  const sources: string[] = [];
  for (const item of items) {
    const name = typeof item.label.name === 'string' ? item.label.name.toLowerCase() : '';
    const rec = map.get(name);
    if (rec === undefined) {
      continue;
    }
    const display = typeof item.label.name === 'string' && item.label.name !== '' ? item.label.name : 'Unknown';
    if (rec.mg > 0) {
      totalMg += rec.mg * readScale(item, overrides);
      if (!sources.includes(display)) {
        sources.push(display);
      }
    }
    else if (rec.present) {
      present = true;
      if (!sources.includes(display)) {
        sources.push(display);
      }
    }
  }
  return { totalMg, present, sources };
}

// ─── Essential-fatty-acid aggregate (EFA coverage) ─────────────────────────
// omega-3 + omega-6 have no individual Wallach dose: he states ONE amount for the
// essential fatty acids as a CATEGORY ("supplemented at the rate of 9 grams per day
// in capsule form", WAL-CLM-DDDL-000115), and his EFAs are exactly two — "only two
// (linoleic and linolenic) are designated as Essential Fatty Acids". So they share
// ONE meter, Σ(regimen efa_oil_mg) / goal, exactly as the 33 rare-earths share the
// PDM meter. The goal + per-product mg are GENERATED (efa_coverage_derive.py) from
// the sealed pillars; omega-9 is NOT a member (Wallach never names oleic acid an EFA).
// ★ The measure is OIL mass: Wallach writes "essential fatty acids AS FLAXSEED OIL at
// 9 grams per day", so 9 one-gram softgels IS his dose. Summing the named acids would
// demand ~12.7 and make his requirement 40% harder than he wrote it.
const EFA: EfaCoverage = EfaCoverageSchema.parse(efaCoverageData);
const EFA_GOAL = EFA.goal.maintenance_mg;

let cachedEfaByName: Map<string, number> | null = null;
function efaByName(): Map<string, number> {
  if (cachedEfaByName === null) {
    const m = new Map<string, number>();
    for (const rec of Object.values(EFA.products)) {
      const nm = rec.canonical_name.toLowerCase();
      if (nm !== '') {
        m.set(nm, rec.efa_oil_mg);
      }
    }
    cachedEfaByName = m;
  }
  return cachedEfaByName;
}

interface EfaDelivery {
  totalMg: number;
  sources: string[];
}

/**
 * Aggregate essential-fatty-acid delivery across the effective regimen: sum each
 * item's EFA mg (serving-scaled), matched by canonical name — the same join the PDM
 * aggregate and the auto-heal use. This ONE aggregate scores both omega tiles.
 */
function efaAggregate(items: RegimenItem[], overrides: OverridesMap): EfaDelivery {
  const map = efaByName();
  let totalMg = 0;
  const sources: string[] = [];
  for (const item of items) {
    const name = typeof item.label.name === 'string' ? item.label.name.toLowerCase() : '';
    const mg = map.get(name);
    if (mg === undefined || mg <= 0) {
      continue;
    }
    totalMg += mg * readScale(item, overrides);
    const display = typeof item.label.name === 'string' && item.label.name !== '' ? item.label.name : 'Unknown';
    if (!sources.includes(display)) {
      sources.push(display);
    }
  }
  return { totalMg, sources };
}

/** The shared EFA verdict from the aggregate (mirrors the pdm/numericStatus thresholds). */
function efaStatusOf(e: EfaDelivery): CoverageStatus {
  if (EFA_GOAL <= 0) {
    return '';
  }
  if (e.totalMg >= EFA_GOAL * 0.95) {
    return 'covered';
  }
  if (e.totalMg >= EFA_GOAL * 0.30) {
    return 'partial';
  }
  return e.totalMg > 0 ? 'gap' : '';
}

/** The shared trace_pdm verdict from the aggregate (mirrors numericStatus thresholds). */
function pdmStatusOf(p: PdmDelivery): CoverageStatus {
  if (PDM_GOAL <= 0) {
    return '';
  }
  if (p.totalMg >= PDM_GOAL * 0.95) {
    return 'covered';
  }
  if (p.totalMg >= PDM_GOAL * 0.30) {
    return 'partial';
  }
  if (p.totalMg > 0) {
    return 'gap';
  }
  return p.present ? 'present' : '';
}

/**
 * Sum every regimen item's label nutrients into per-essential mg/IU totals.
 * Each label nutrient resolves to a canon slug via the registry resolver, then
 * to its target by slug — so the Coverage math credits the SAME essential the
 * Products pillar does (one resolution truth).
 */
function accumulate(
  items: RegimenItem[],
  overrides: OverridesMap,
  targets: Essential[],
  bySlug: Map<string, Essential>,
): Map<string, Delivery> {
  const out = new Map<string, Delivery>();
  for (const t of targets) {
    out.set(t.name, { totalMg: 0, totalIU: 0, sources: [] });
  }
  for (const item of items) {
    const scale = readScale(item, overrides);
    const displayName = typeof item.label.name === 'string' && item.label.name !== ''
      ? item.label.name
      : 'Unknown';
    const rawNutrients = liveNutrients(item);
    for (const raw of rawNutrients) {
      const parsed = RegimenNutrientSchema.safeParse(raw);
      if (!parsed.success) {
        continue;
      }
      const n = parsed.data;
      if (!(n.amount > 0)) {
        continue;
      }
      const slug = resolveSlug(n.name, n.form ?? null);
      if (slug === null) {
        continue;
      }
      const matched = bySlug.get(slug);
      if (matched === undefined) {
        continue;
      }
      const d = out.get(matched.name);
      if (d === undefined) {
        continue;
      }
      const conv = toMg(n.amount * scale, n.unit, matched.slug);
      if (conv.u === 'iu') {
        d.totalIU += conv.v;
      }
      else {
        d.totalMg += conv.v;
      }
      if (!d.sources.includes(displayName)) {
        d.sources.push(displayName);
      }
    }
  }
  return out;
}

// ─── Classification (legacy classifyLive port) ─────────────────────────────

function numericStatus(target: CoverageTarget, d: Delivery): CoverageStatus {
  const isIU = (target.unit ?? '').toLowerCase() === 'iu';
  const current = isIU ? d.totalIU : d.totalMg;
  const lowRaw = target.low ?? 0;
  const low = isIU ? lowRaw : toMg(lowRaw, target.unit).v;
  if (low <= 0) {
    // Deliberate §00.A deviation from legacy (which returned 'ok'): no defined
    // floor + nothing delivered ⇒ pending, never a free "covered".
    return current > 0 ? 'covered' : '';
  }
  if (current >= low * 0.95) {
    return 'covered';
  }
  if (current >= low * 0.30) {
    return 'partial';
  }
  return 'gap';
}

/**
 * The 4 organic building blocks (hydrogen · carbon · nitrogen · oxygen) are present in
 * air/water/food by default (Luneth), so a '' (no-dose) status reads covered, not absent.
 *
 * PROMOTED to the state layer 2026-07-14. It previously lived ONLY in views/knowledge.ts
 * (as a symbol set applied inside the drawer's dot mapper), which meant the drawer painted
 * H/C/N/O green while Coverage rendered the same four tiles blank — two surfaces disagreeing
 * about 4 essentials over ONE snapshot. A coverage verdict is a state decision, never a view
 * decision; both surfaces now inherit this from the snapshot. Keyed by canon slug (not the
 * display symbol) so it joins the same way every other target does.
 */
const FOUNDATIONAL_PRESENT_SLUGS: ReadonlySet<string> = new Set([
  'hydrogen',
  'carbon',
  'nitrogen',
  'oxygen',
]);

function classify(
  target: CoverageTarget | null,
  d: Delivery,
  pdmStatus: CoverageStatus,
  efaStatus: CoverageStatus,
): CoverageStatus {
  const hasSrc = d.sources.length > 0;
  const kind = target?.kind;
  if (target === null || kind === undefined || kind === 'unspecified') {
    return hasSrc ? 'covered' : '';
  }
  if (kind === 'dietary') {
    return hasSrc ? 'covered' : '';
  }
  if (kind === 'trace_pdm') {
    // The 33 trace_pdm rare-earths share ONE verdict from the plant-derived-mineral
    // aggregate (Σ vehicle mg / goal), computed once per recompute — not per mineral
    // (no product label itemizes a rare earth). silver/tin/cobalt carry their own
    // Wallach dose → kind 'wallach' → the numeric path below, never here.
    return pdmStatus;
  }
  if (kind === 'wallach_collective') {
    // ★ THIS BRANCH WAS 'trace_pdm || wallach_collective' AND IT WAS A BEARTRAP.
    // wallach_collective was a DEAD alias — no target carried it — so it sat here
    // harmlessly routing to the RARE-EARTH mineral meter. The moment targets_derive
    // started emitting it for the omegas (2026-07-15), seeding two plant-derived
    // MINERAL products with ZERO fatty acids rendered OMEGA-3 and OMEGA-6 as
    // "covered" — proven with a DOM probe, not reasoned about. A dead alias is not
    // inert; it is a loaded branch waiting for someone to feed it.
    // Every collective group MUST route to its own meter, keyed by the group the
    // claim names. No group => no verdict, never a neighbouring group's.
    if (target.collective_group === 'essential-fatty-acids') {
      return efaStatus;
    }
    return '';
  }
  if (kind === 'dietary_with_clinical_lever') {
    if (target.low !== undefined && target.low > 0) {
      return numericStatus(target, d);
    }
    return hasSrc ? 'covered' : '';
  }
  // Numeric: hbsp · wallach · wallach_clinical · any kind carrying low/unit.
  return numericStatus(target, d);
}

function deliveryRatio(target: CoverageTarget | null, status: CoverageStatus, d: Delivery): number {
  if (target === null) {
    return status === 'covered' || status === 'trace' ? 1 : 0;
  }
  const isIU = (target.unit ?? '').toLowerCase() === 'iu';
  const current = isIU ? d.totalIU : d.totalMg;
  const lowRaw = target.low ?? 0;
  const low = isIU ? lowRaw : toMg(lowRaw, target.unit).v;
  if (low > 0) {
    return current / low;
  }
  return status === 'covered' || status === 'trace' ? 1 : 0;
}

// ─── Cache + recompute ─────────────────────────────────────────────────────

let cachedSnapshot: CoverageSnapshot | null = null;

/** Recompute coverage from the targets DB + the active regimen. */
export function recompute(): CoverageSnapshot {
  const targets = readTargets();
  const bySlug = buildBySlug(targets);
  const overrides = loadRgOverrides();
  const items = loadEffectiveRegimen();
  const delivery = accumulate(items, overrides, targets, bySlug);
  const pdm = pdmAggregate(items, overrides);
  const pdmStatus = pdmStatusOf(pdm);
  const efa = efaAggregate(items, overrides);
  const efaStatus = efaStatusOf(efa);

  const tiles: CoverageTile[] = targets.map((entry) => {
    const target = CoverageTargetSchema.safeParse(entry.target);
    const t = target.success ? target.data : null;
    const d = delivery.get(entry.name) ?? EMPTY_DELIVERY;
    // The foundational-present rule runs HERE (not inside classify) because it keys off the
    // essential's identity, not its target/delivery — classify() only sees the target + delivery.
    const classified = classify(t, d, pdmStatus, efaStatus);
    const status: CoverageStatus = (classified === '' && FOUNDATIONAL_PRESENT_SLUGS.has(entry.slug))
      ? 'covered'
      : classified;
    // NOT `|| wallach_collective` — that alias fed the omegas into the rare-earth
    // meter (see classify). trace_pdm is the ONLY kind the PDM aggregate scores.
    const isPdm = t?.kind === 'trace_pdm';
    let intakeVsTarget: CoverageTile['intakeVsTarget'] = null;
    if (isPdm) {
      // The rare-earth group reads Σ vehicle mg against the ONE shared goal (the meter
      // the inner page shows) — no per-mineral number exists. Null when nothing
      // plant-derived is in the stack, so the view stays quiet on a bare regimen.
      if (pdm.totalMg > 0) {
        intakeVsTarget = {
          deliveredAmount: Math.round(pdm.totalMg * 10) / 10,
          targetLow: PDM_GOAL,
          targetHigh: PDM_GOAL,
          unit: 'mg',
        };
      }
    }
    else if (t !== null && typeof t.low === 'number' && t.low > 0) {
      intakeVsTarget = {
        deliveredAmount: deliveredInUnit(d, t.unit),
        targetLow: t.low,
        targetHigh: typeof t.high === 'number' ? t.high : t.low,
        unit: t.unit ?? 'mg',
      };
    }
    const base = {
      tileId: buildTileId(entry.name),
      category: catFromTarget(entry.category),
      symbol: '',
      name: entry.name,
      status,
      covered: status === 'covered' || status === 'trace',
      fillPercent: isPdm ? (PDM_GOAL > 0 ? pdm.totalMg / PDM_GOAL : 0) : deliveryRatio(t, status, d),
      coveredBy: isPdm ? pdm.sources : d.sources,
      aggregateVehicle: isPdm && status === 'covered',
      intakeVsTarget,
    };
    return { ...base, pdmGroup: isPdm };
  });

  // Tally by category.
  const byCategory: CoverageSnapshot['byCategory'] = {};
  for (const tile of tiles) {
    const bucket = byCategory[tile.category] ?? { total: 0, covered: 0 };
    bucket.total += 1;
    if (tile.covered) {
      bucket.covered += 1;
    }
    byCategory[tile.category] = bucket;
  }

  const countedTiles = tiles.filter(t => !NON_ESSENTIAL_NAMES.has(t.name));
  const coveredCount = countedTiles.filter(t => t.covered).length;
  const totalCount = countedTiles.length;
  cachedSnapshot = {
    tiles,
    pdmGroup: {
      deliveredMg: Math.round(pdm.totalMg * 10) / 10,
      goalMg: PDM_GOAL,
      status: pdmStatus,
      sources: pdm.sources,
    },
    coveredCount,
    totalCount,
    computedAt: new Date().toISOString(),
    byCategory,
  };

  emit('coverage:recomputed', { coveredCount, totalCount });
  return cachedSnapshot;
}

/** Last cached snapshot. Returns null if recompute() hasn't run yet. */
export function getSnapshot(): CoverageSnapshot | null {
  return cachedSnapshot;
}

/** Get a snapshot, computing if needed. Useful for first-render. */
export function getOrCompute(): CoverageSnapshot {
  return cachedSnapshot ?? recompute();
}

// ─── Shared accessors for the scanner verdict engine (Chunk 6b) ────────────

let cachedTargets: Essential[] | null = null;
let cachedBySlug: Map<string, Essential> | null = null;

function ensureTargets(): void {
  if (cachedTargets === null) {
    cachedTargets = readTargets();
    cachedBySlug = buildBySlug(cachedTargets);
  }
}

/** The Wallach targets DB (cached). Shared with state/scanner.ts. */
export function getTargets(): Essential[] {
  ensureTargets();
  return cachedTargets ?? [];
}

/**
 * Match a nutrient/label name to its essential via the SAME registry resolver
 * the live classifier uses — so the scanner's gap-fill math lines up with the
 * Coverage surface (one resolver, no drift).
 */
export function matchEssential(name: string): Essential | null {
  ensureTargets();
  if (cachedBySlug === null) {
    return null;
  }
  const slug = resolveSlug(name);
  if (slug === null) {
    return null;
  }
  return cachedBySlug.get(slug) ?? null;
}

/**
 * Per-essential delivery (mg + IU) from the current EFFECTIVE regimen — the
 * same accumulation the snapshot is built from. The scanner subtracts this from
 * each Wallach target to compute how much a scanned product still fills.
 */
export function currentDelivery(): Map<string, { totalMg: number; totalIU: number }> {
  ensureTargets();
  if (cachedTargets === null || cachedBySlug === null) {
    return new Map();
  }
  const full = accumulate(loadEffectiveRegimen(), loadRgOverrides(), cachedTargets, cachedBySlug);
  const out = new Map<string, { totalMg: number; totalIU: number }>();
  for (const [k, v] of full) {
    out.set(k, { totalMg: v.totalMg, totalIU: v.totalIU });
  }
  return out;
}

// ─── Wire to regimen changes ───────────────────────────────────────────────

let wireInstalled = false;

/**
 * Install the recompute trigger: regimen changes → coverage recomputes.
 * Idempotent — main.ts calls this once at boot.
 */
export function installRecomputeTrigger(): void {
  if (wireInstalled) {
    return;
  }
  wireInstalled = true;

  on('regimen:changed', () => recompute());

  // Also listen to native storage events for cross-tab sync of regimen LS keys.
  onChange((key) => {
    if (key.startsWith('rgSlot') || key === 'lcRegimen_v1') {
      recompute();
    }
  });

  /*
   * Round 150 §31 hook for legacy code: when legacy fires its
   * window.triggerRegimenRerender, also trigger our recompute. Backward
   * compatibility with the legacy event-cascade discipline.
   */
  const w = window as Window & { triggerRegimenRerender?: () => void };
  const original = w.triggerRegimenRerender;
  if (typeof original === 'function') {
    w.triggerRegimenRerender = () => {
      try {
        original();
      }
      finally {
        recompute();
      }
    };
  }
}
