// ─── Live-composition auto-heal ─────────────────────────────────
// A regimen item stores a SNAPSHOT of its product's nutrients at add-time. If the
// sealed Product DB later corrects a value, that snapshot goes stale and the user
// would have to re-add the item to pick up the fix. Instead: for any item that came
// from the catalog (NOT a user-scanned label) whose name still matches a live
// product, we re-read the CURRENT composition from the SAME vault the add-picker
// uses (regimen-label-lookup) at compute time, so the number self-corrects on the
// next render with no re-adding. The match is EXACT on the lowercased canonical
// name -- addItem (views/regimen.ts) stores label.name = the vault's canonical_name
// verbatim, so a user-scanned custom item (or the base foundation, whose legacy
// names differ) never collides and always keeps its own data.
let cachedVaultNutrients: Map<string, unknown[]> | null = null;
function vaultNutrientsByName(): Map<string, unknown[]> {
  if (cachedVaultNutrients === null) {
    const m = new Map<string, unknown[]>();
    const root: unknown = (regimenLabelLookup as { products?: unknown }).products ?? regimenLabelLookup;
    if (root !== null && typeof root === 'object') {
      for (const value of Object.values(root as Record<string, unknown>)) {
        for (const cand of (Array.isArray(value) ? value : [value])) {
          if (cand !== null && typeof cand === 'object') {
            const c = cand as { canonical_name?: unknown; name?: unknown; nutrients?: unknown };
            const nm = typeof c.canonical_name === 'string'
              ? c.canonical_name
              : (typeof c.name === 'string' ? c.name : undefined);
            if (nm !== undefined && Array.isArray(c.nutrients)) {
              m.set(nm.toLowerCase(), c.nutrients);
            }
          }
        }
      }
    }
    cachedVaultNutrients = m;
  }
  return cachedVaultNutrients;
}

/**
 * The composition to credit for an item: the LIVE vault nutrients when the item
 * came from the catalog and still matches a product (auto-heal), else the item's
 * own stored snapshot (user-supplied and custom items and the base foundation keep
 * their data). No write-back -- the heal is a read-time re-resolution.
 *
 * The user-supplied test is core/provenance's, never a token compared here: a scanned
 * OR typed item's amounts are the user's own reading of a label, and healing one whose
 * name happens to collide with a vault product would REPLACE those amounts with sealed
 * composition — silently, with no error and no mark on screen.
 */
export function liveNutrients(item: RegimenItem): unknown[] {
  const snapshot = Array.isArray(item.label.nutrients) ? item.label.nutrients : [];
  if (isUserSupplied(item.provenance)) {
    return snapshot;
  }
  // A catalog FOOD heals from the food catalog, never from the product vault. It must not
  // fall through to the name lookup below: food display names are curated ("Butter",
  // "Salt") and a collision with a Youngevity product name would silently credit that
  // PRODUCT's composition to a plate of food. Keyed by id for that reason, not by name.
  if (isFoodCatalog(item.provenance)) {
    const foodId = item.label['food_id'];
    const rows = typeof foodId === 'string' ? foodNutrientRows(foodId) : [];
    return rows.length > 0 ? rows : snapshot;
  }
  const name = typeof item.label.name === 'string' ? item.label.name.toLowerCase() : '';
  return vaultNutrientsByName().get(name) ?? snapshot;
}

/**
 * Resolve an item's serving/dose scaling factor: override → label.servings → 1.
 *
 * WHY THERE IS NO ITEM-LEVEL CANDIDATE: reading
 * `(item as Record<string, unknown>)['scaling_factor']` between the two below can NEVER
 * fire. `RegimenItemSchema` is a plain `z.object()` (core/schemas/regimen.ts) — Zod STRIPS
 * unknown keys — so an item-level `scaling_factor` is gone before readScale is ever
 * called. Parsing `{…, scaling_factor: 7}` yields `undefined` for it while
 * `label.servings` survives, because `RegimenLabelSchema` alone is `.passthrough()`. Any
 * doc or test that treats "override → item → label.servings" as a working chain will see
 * every dose grade identically and no error. If an item-level factor is ever wanted, the
 * schema must opt in first — do not re-add the read.
 */
function readScale(item: RegimenItem, overrides: OverridesMap): number {
  const ov = overrides[String(item.id)];
  const candidates: unknown[] = [
    ov?.['scaling_factor'],
    (item.label as Record<string, unknown>)['servings'],
  ];
  for (const c of candidates) {
    const n = typeof c === 'number' ? c : typeof c === 'string' ? Number.parseFloat(c) : Number.NaN;
    if (Number.isFinite(n) && n > 0) {
      return n;
    }
  }
  return 1;
}

// ─── Plant-derived mineral aggregate (PDM coverage) ────────────────────────
// The 34 trace_pdm minerals have no individual Wallach dose; they are covered
// as ONE group by plant-derived-mineral intake — Σ(vehicle mg) / goal. Goal +
// per-product vehicle mg are GENERATED (pdm_coverage_derive.py) from the sealed
// pillar (composition) + the curated judgment + Wallach's sealed dose claim.
const PDM = PdmCoverageSchema.parse(pdmCoverageData);
const PDM_GOAL = PDM.goal.maintenance_mg;

/**
 * Rare-earth-group best sources: plant-derived-mineral products ranked by vehicle mg,
 * highest first. pdm_mg is product COMPOSITION, never a target; present-only vehicles
 * (no derivable mg) are excluded.
 */
export function rankedPdmSources(): { productId: string; name: string; mg: number }[] {
  return Object.entries(PDM.products)
    .filter(([, r]) => r.pdm_mg > 0)
    .map(([productId, r]) => ({ productId, name: r.canonical_name, mg: r.pdm_mg }))
    .sort((a, b) => b.mg - a.mg);
}

/**
 * The goal's derivation numbers (provenance) for the "how is this calculated?" hover —
 * read straight from the sealed pillar+claim projection, never re-typed in a view.
 */
export function pdmGoalProvenance(): {
  doseAmount: number;
  doseUnit: string;
  perBwLb: number;
  refMg: number;
  bodyWeightLb: number;
  goalMg: number;
} {
  const p = (PDM.goal as { provenance?: Record<string, number | string> }).provenance ?? {};
  return {
    doseAmount: Number(p['wallach_dose_amount'] ?? 1),
    doseUnit: String(p['wallach_dose_unit'] ?? 'fl oz'),
    perBwLb: Number(p['wallach_dose_per_body_weight_lb'] ?? 100),
    refMg: Number(p['reference_mg_per_fl_oz'] ?? 0),
    bodyWeightLb: Number(p['body_weight_lb'] ?? 154),
    goalMg: PDM_GOAL,
  };
}

let cachedPdmByName: Map<string, { mg: number; present: boolean }> | null = null;
function pdmByName(): Map<string, { mg: number; present: boolean }> {
  if (cachedPdmByName === null) {
    const m = new Map<string, { mg: number; present: boolean }>();
    for (const rec of Object.values(PDM.products)) {
      const nm = rec.canonical_name.toLowerCase();
      if (nm !== '') {
        m.set(nm, { mg: rec.pdm_mg, present: rec.present });
      }
    }
    cachedPdmByName = m;
  }
  return cachedPdmByName;
}

interface PdmDelivery {
  totalMg: number;
  present: boolean;
  sources: string[];
}

/**
 * Aggregate plant-derived-mineral delivery across the effective regimen: sum each
 * item's vehicle mg (serving-scaled), OR-ing the present-but-unquantified flag.
 * Matched by canonical name (the same join the auto-heal uses). This ONE aggregate
 * scores all 34 trace_pdm tiles (they have no per-mineral delivery of their own).
 */
function pdmAggregate(items: RegimenItem[], overrides: OverridesMap): PdmDelivery {
  const map = pdmByName();
  let totalMg = 0;
  let present = false;
  const sources: string[] = [];
  for (const item of items) {
    const name = typeof item.label.name === 'string' ? item.label.name.toLowerCase() : '';
    const rec = map.get(name);
    if (rec === undefined) {
      continue;
    }
    const display = typeof item.label.name === 'string' && item.label.name !== '' ? item.label.name : 'Unknown';
    if (rec.mg > 0) {
      totalMg += rec.mg * readScale(item, overrides);
      if (!sources.includes(display)) {
        sources.push(display);
      }
    }
    else if (rec.present) {
      present = true;
      if (!sources.includes(display)) {
        sources.push(display);
      }
    }
  }
  return { totalMg, present, sources };
}

// ─── Essential-fatty-acid aggregate (EFA coverage) ─────────────────────────
// omega-3 + omega-6 have no individual Wallach dose: he states ONE amount for the
// essential fatty acids as a CATEGORY ("supplemented at the rate of 9 grams per day
// in capsule form", WAL-CLM-DDDL-000115), and his EFAs are exactly two — "only two
// (linoleic and linolenic) are designated as Essential Fatty Acids". So they share
// ONE meter, Σ(regimen efa_oil_mg) / goal, exactly as the 34 plant-derived minerals share the
// PDM meter. The goal + per-product mg are GENERATED (efa_coverage_derive.py) from
// the sealed pillars; omega-9 is NOT a member (Wallach never names oleic acid an EFA).
// ★ The measure is OIL mass: Wallach writes "essential fatty acids AS FLAXSEED OIL at
// 9 grams per day", so 9 one-gram softgels IS his dose. Summing the named acids would
// demand ~12.7 and make his requirement 40% harder than he wrote it.
const EFA: EfaCoverage = EfaCoverageSchema.parse(efaCoverageData);
const EFA_GOAL = EFA.goal.maintenance_mg;

