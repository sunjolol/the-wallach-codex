  intakeVsTarget: {
    deliveredAmount: number;
    targetLow: number;
    targetHigh: number;
    unit: string;
  } | null;
  /** True for a trace_pdm / wallach_collective rare-earth-group tile (scored as one group). */
  pdmGroup: boolean;
