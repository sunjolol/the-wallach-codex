// ─── Category + id helpers ─────────────────────────────────────────────────

/**
 * Map the targets-DB coarse category to our TileCategory. Mineral subsection
 * granularity (FOUNDATIONAL / INDIVIDUALLY DOSED / PLANT DERIVED) lives in the
 * layout, not the targets DB, so minerals collapse to `other` here — `byCategory`
 * is a tally aid, not a render source (views read the layout for section grouping).
 * Do NOT re-introduce mineral tier buckets ('foundational' / 'major-trace' / 'rare-trace')
 * into this union: this function collapses every mineral to 'other' so nothing would emit
 * them, and they name a tier scheme Wallach never wrote.
 */
function catFromTarget(raw: string): TileCategory {
  switch (raw) {
    case 'vitamins':
      return 'vitamins';
    case 'amino_acids':
      return 'aminos';
    case 'fatty_acids':
      return 'fatty-acids';
    default:
      return 'other';
  }
}

function buildTileId(name: string): TileId {
  return `tile_${name.toLowerCase().replace(/\W+/g, '_')}`;
}

// ─── Essential membership — single source for the "90" count ───────────────

/**
 * The periodic-table presentation layout. Single source for which essentials
 * exist and which count toward Wallach's 90: a tile flagged `essential: false`
 * (Omega-9 / oleic — body-synthesizable) is shown for completeness but NOT
 * counted. The targets-DB embed carries the per-essential dose; the layout
 * carries essentiality. §00.A: the count traces to Wallach's "90 Essential
 * Nutrients" enumeration (60 minerals + 16 vitamins + 12 amino acids + 2 EFAs).
 */
const LAYOUT = CoverageLayoutSchema.parse(coverageLayoutData);

function layoutTiles(): readonly LayoutTile[] {
  return LAYOUT.sections.flatMap(s =>
    s.subsections !== undefined
      ? s.subsections.flatMap(sub => sub.tiles)
      : (s.tiles ?? []),
  );
}

/** Canonical names the layout marks non-essential — excluded from the count. */
const NON_ESSENTIAL_NAMES: ReadonlySet<string> = new Set(
  layoutTiles().filter(t => t.essential === false).map(t => t.key),
);

/** Count of Wallach essentials (layout tiles where `essential !== false`) — 90. */
export function essentialCount(): number {
  return layoutTiles().filter(t => t.essential !== false).length;
}

/** Layout tile by its `key` (= layout_key / canonical name) — built once. */
let tileByKey: Map<string, LayoutTile> | null = null;
function tileIndex(): Map<string, LayoutTile> {
  if (tileByKey === null) {
    tileByKey = new Map(layoutTiles().map(t => [t.key, t]));
  }
  return tileByKey;
}

/**
 * The compact tile glyph for an essential, by its layout_key: the chemical
 * symbol (minerals), vitamin letter, or amino abbreviation from the periodic
 * layout; ω3/ω6/ω9 for the fatty acids (no short code in the layout); '' if none.
 */
export function essentialGlyph(layoutKey: string): string {
  const t = tileIndex().get(layoutKey);
  const g = t?.sym ?? t?.letter ?? t?.abbr;
  if (g !== undefined && g.length > 0) {
    return g;
  }
  const omega = /^Omega-([369])\b/.exec(layoutKey);
  return omega !== null ? `ω${omega[1]}` : '';
}

