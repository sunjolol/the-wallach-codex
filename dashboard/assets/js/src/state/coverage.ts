let cachedSnapshot: CoverageSnapshot | null = null;

/** What buildTiles() returns: the tile set plus the shared PDM aggregate the snapshot re-exports. */
interface BuiltTiles {
  tiles: CoverageTile[];
  pdm: ReturnType<typeof pdmAggregate>;
  pdmStatus: CoverageStatus;
}

/**
 * Build one tile per targets-DB entry (91: the 90 essentials plus the non-essential
 * omega-9, shown for completeness and filtered out of every count) for a GIVEN item list
 * + overrides. Pure: reads only the sealed targets and the passed stack, never active
 * state. recompute() feeds it the active slot; coveredCountForItems() feeds it a saved
 * slot — so a saved slot's count equals exactly what it would read once active (no drift;
 * the count derives from the same truth).
 */
function buildTiles(items: RegimenItem[], overrides: OverridesMap): BuiltTiles {
  const targets = readTargets();
  const bySlug = buildBySlug(targets);
  const delivery = accumulate(items, overrides, targets, bySlug);
  const pdm = pdmAggregate(items, overrides);
  const pdmStatus = pdmStatusOf(pdm);
  const efa = efaAggregate(items, overrides);
  const efaStatus = efaStatusOf(efa);

  const tiles: CoverageTile[] = targets.map((entry) => {
    const target = CoverageTargetSchema.safeParse(entry.target);
    const t = target.success ? target.data : null;
    const d = delivery.get(entry.name) ?? EMPTY_DELIVERY;
    // Two identity-keyed adjustments run HERE (not inside classify) because they key off the
    // essential's identity, not its target/delivery — classify() only sees the target + delivery.
    const classified = classify(t, d, pdmStatus, efaStatus);
    //  · FOUNDATIONAL_PRESENT (H/C/N/O) promote an empty verdict to 'covered' — they ARE among the 90.
    //  · a NON-ESSENTIAL (omega-9) is capped at 'present' and can NEVER read 'covered': Wallach sets no
    //    goal for it, so its grid tile must not light green — that would contradict the entity page's
    //    "not tracked". 'present' = you may be getting it (oleic rides in an EFA oil), not a goal met.
    //    It is already out of coveredCount/totalCount (countedTiles), so this is purely the grid dot.
    let status: CoverageStatus;
    if (NON_ESSENTIAL_NAMES.has(entry.name)) {
      status = (classified === 'covered' || classified === 'trace') ? 'present' : classified;
    }
    else if (classified === '' && FOUNDATIONAL_PRESENT_SLUGS.has(entry.slug)) {
      status = 'covered';
    }
    else {
      status = classified;
    }
    // NOT `|| wallach_collective` — that alias fed the omegas into the rare-earth
    // meter (see classify). trace_pdm is the ONLY kind the PDM aggregate scores.
    const isPdm = t?.kind === 'trace_pdm';
    // The EFA pair grades off the SHARED 9,000 mg aggregate, the same shape as the
    // plant-derived 34 off 924 mg — so it needs the same goal-relative fill. Keyed on the
    // group, never on the kind alone: `wallach_collective` is deliberately routed per
    // group (see classify), because a collective that fell through to a neighbouring
    // group's meter once rendered OMEGA-3 covered off two mineral products carrying zero
    // fatty acids.
    const isEfa = t?.kind === 'wallach_collective' && t.collective_group === 'essential-fatty-acids';
    let intakeVsTarget: CoverageTile['intakeVsTarget'] = null;
    if (isPdm) {
      // The rare-earth group reads Σ vehicle mg against the ONE shared goal (the meter
      // the inner page shows) — no per-mineral number exists. Null when nothing
      // plant-derived is in the stack, so the view stays quiet on a bare regimen.
      if (pdm.totalMg > 0) {
        intakeVsTarget = {
          deliveredAmount: Math.round(pdm.totalMg * 10) / 10,
          targetLow: PDM_GOAL,
          targetHigh: PDM_GOAL,
          unit: 'mg',
        };
      }
    }
    else if (t !== null && typeof t.low === 'number' && t.low > 0) {
      intakeVsTarget = {
        deliveredAmount: deliveredInUnit(d, t.unit),
        targetLow: t.low,
        targetHigh: typeof t.high === 'number' ? t.high : t.low,
        unit: t.unit ?? 'mg',
      };
    }
    // Why there is no number - DELIBERATE cases only, so the view never shows the "unmined gap"
    // copy for an essential whose absence is by design. A genuinely unmined essential is status ''
    // with no match here -> stays null -> generic copy. Non-essential wins over present (an
    // omega-9 is body-made, not "covered by default").
    let noTargetReason: NoTargetReason = null;
    if (NON_ESSENTIAL_NAMES.has(entry.name)) {
      noTargetReason = 'non_essential';
    }
    else if (t?.kind !== 'mirrors' && !isPdm && intakeVsTarget === null) {
      if (typeof t?.low === 'number' && t.low === 0) {
        noTargetReason = 'present_stated_zero';
      }
      else if (FOUNDATIONAL_PRESENT_SLUGS.has(entry.slug)) {
        noTargetReason = 'present_structural';
      }
    }
    const base = {
      tileId: buildTileId(entry.name),
      category: catFromTarget(entry.category),
      symbol: '',
      name: entry.name,
      status,
      covered: status === 'covered' || status === 'trace',
      // Both aggregate meters fill against their own goal; everything else measures its
      // own delivery against its own Wallach low. deliveryRatio cannot serve the
      // aggregates: they carry no numeric `low`, so it returns a binary 0/1 and the bar
      // snaps from empty to full instead of showing progress.
      fillPercent: isPdm
        ? (PDM_GOAL > 0 ? pdm.totalMg / PDM_GOAL : 0)
        : isEfa
          ? (EFA_GOAL > 0 ? efa.totalMg / EFA_GOAL : 0)
          : deliveryRatio(t, status, d),
      // Same reasoning for the sources line: an EFA tile's contributors are the products
      // feeding the shared oil total, not this one tile's own nutrient rows.
      contributesTo: isPdm ? pdm.sources : isEfa ? efa.sources : d.sources,
      aggregateVehicle: isPdm && status === 'covered',
      intakeVsTarget,
      noTargetReason,
    };
    // pdmGroup/mirrorsOf/mirrorsSlug sit here rather than in `base` because all three are
    // resolved at ASSEMBLY time (the mirrors pass below writes the latter two), not from this
    // essential's own target/delivery like every field above.
    return { ...base, pdmGroup: isPdm, mirrorsOf: null, mirrorsSlug: null };
  });

  // ── MIRRORS — second pass ─────────────────────────────────────────────────
  // An essential with target.kind 'mirrors' states no amount of its own; Wallach's position
  // is that its requirement is met through another essential, so it carries that verdict.
  //
  // WHY A PASS AND NOT A classify() BRANCH: classify() sees one target + one delivery. A
  // mirror needs a DIFFERENT essential's finished verdict, which does not exist until every
  // non-mirror tile is classified. Keeping it out here preserves classify()'s property that a
  // verdict is a pure function of that essential's own inputs — the thing that lets a reader
  // reason about one tile in isolation.
  //
  // Runs BEFORE the tallies below on purpose: `covered` feeds byCategory + coveredCount, so a
  // mirror must settle before it is counted, or the headline stat disagrees with the tile.
  //
  // Single hop, no cycles: mirrors_resolve (tools/invariants.py) proves the named slug exists
  // and is not itself a mirror, so this cannot chain or loop. Every lookup below fails CLOSED
  // (leaves the tile statusless) rather than guessing.
  const nameBySlug = new Map(targets.map(e => [e.slug, e.name]));
  const statusByName = new Map(tiles.map(t => [t.name, t.status]));
  targets.forEach((entry, i) => {
    const parsed = CoverageTargetSchema.safeParse(entry.target);
    if (!parsed.success || parsed.data.kind !== 'mirrors') {
      return;
    }
    const srcSlug = parsed.data.mirrors_slug;
    const srcName = srcSlug !== undefined ? nameBySlug.get(srcSlug) : undefined;
    const srcStatus = srcName !== undefined ? statusByName.get(srcName) : undefined;
    const tile = tiles[i];
    if (srcName === undefined || srcStatus === undefined || tile === undefined) {
      return;
    }
    tile.status = srcStatus;
    tile.covered = srcStatus === 'covered' || srcStatus === 'trace';
    tile.fillPercent = tiles.find(t => t.name === srcName)?.fillPercent ?? 0;
    tile.mirrorsOf = srcName;
    tile.mirrorsSlug = srcSlug ?? null;
  });

  return { tiles, pdm, pdmStatus };
}

/**
 * Covered-count for an ARBITRARY slot's items — the SAME engine recompute uses, so a
 * saved slot's number equals what it would show once active (no drift). Pure; the
 * Regimen cockpit reads it to paint each save-slot's coverage without switching slots.
 */
export function coveredCountForItems(items: RegimenItem[], overrides: OverridesMap): number {
  const { tiles } = buildTiles(items, overrides);
  return tiles.filter(t => !NON_ESSENTIAL_NAMES.has(t.name) && t.covered).length;
}

/** Recompute coverage from the targets DB + the active regimen, and cache the snapshot. */
export function recompute(): CoverageSnapshot {
  const items = loadEffectiveRegimen();
  const overrides = loadRgOverrides();
  const { tiles, pdm, pdmStatus } = buildTiles(items, overrides);

  // Tally by category.
  const byCategory: CoverageSnapshot['byCategory'] = {};
  for (const tile of tiles) {
    // Non-essentials (omega-9 / oleic) are shown for completeness but are NOT one of
    // the 90 -- skip them so the category totals sum to totalCount (90), the same filter
    // coveredCount/totalCount use below. Otherwise Fatty acids reads /3 (categories = 91).
    if (NON_ESSENTIAL_NAMES.has(tile.name)) {
      continue;
    }
    const bucket = byCategory[tile.category] ?? { total: 0, covered: 0 };
    bucket.total += 1;
    if (tile.covered) {
      bucket.covered += 1;
    }
    byCategory[tile.category] = bucket;
  }

  const countedTiles = tiles.filter(t => !NON_ESSENTIAL_NAMES.has(t.name));
  const coveredCount = countedTiles.filter(t => t.covered).length;
  const totalCount = countedTiles.length;
  cachedSnapshot = {
    tiles,
    pdmGroup: {
      deliveredMg: Math.round(pdm.totalMg * 10) / 10,
      goalMg: PDM_GOAL,
      status: pdmStatus,
      sources: pdm.sources,
    },
    coveredCount,
    totalCount,
    computedAt: new Date().toISOString(),
    byCategory,
  };

  emit('coverage:recomputed', { coveredCount, totalCount });
  return cachedSnapshot;
}

/** Last cached snapshot. Returns null if recompute() hasn't run yet. */
export function getSnapshot(): CoverageSnapshot | null {
  return cachedSnapshot;
}

/** Get a snapshot, computing if needed. Useful for first-render. */
export function getOrCompute(): CoverageSnapshot {
  return cachedSnapshot ?? recompute();
}

// ─── Shared accessors for the scanner verdict engine ─────────────────────

let cachedTargets: Essential[] | null = null;
let cachedBySlug: Map<string, Essential> | null = null;

function ensureTargets(): void {
  if (cachedTargets === null) {
    cachedTargets = readTargets();
    cachedBySlug = buildBySlug(cachedTargets);
  }
}

/** The Wallach targets DB (cached). Shared with state/scanner.ts. */
export function getTargets(): Essential[] {
  ensureTargets();
  return cachedTargets ?? [];
}

/**
 * Match a nutrient/label name to its essential via the SAME registry resolver
 * the live classifier uses — so the scanner's gap-fill math lines up with the
 * Coverage surface (one resolver, no drift).
 */
export function matchEssential(name: string): Essential | null {
  ensureTargets();
  if (cachedBySlug === null) {
    return null;
  }
  const slug = resolveSlug(name);
  if (slug === null) {
    return null;
  }
  return cachedBySlug.get(slug) ?? null;
}

/**
 * Per-essential delivery (mg + IU) from the current EFFECTIVE regimen — the
 * same accumulation the snapshot is built from. The scanner subtracts this from
 * each Wallach target to compute how much a scanned product still fills.
 */
export function currentDelivery(): Map<string, { totalMg: number; totalIU: number }> {
  ensureTargets();
  if (cachedTargets === null || cachedBySlug === null) {
    return new Map();
  }
  const full = accumulate(loadEffectiveRegimen(), loadRgOverrides(), cachedTargets, cachedBySlug);
  const out = new Map<string, { totalMg: number; totalIU: number }>();
  for (const [k, v] of full) {
    out.set(k, { totalMg: v.totalMg, totalIU: v.totalIU });
  }
  return out;
}

// ─── Wire to regimen changes ───────────────────────────────────────────────

let wireInstalled = false;

/**
 * Install the recompute trigger: regimen changes → coverage recomputes.
 * Idempotent — main.ts calls this once at boot.
 */
export function installRecomputeTrigger(): void {
  if (wireInstalled) {
    return;
  }
  wireInstalled = true;

  on('regimen:changed', () => recompute());

  // Also listen to native storage events for cross-tab sync of regimen LS keys.
  onChange((key) => {
    if (key.startsWith('rgSlot') || key === 'lcRegimen_v1') {
      recompute();
    }
  });

  /*
   * Compatibility shim: if any script on the page installs a global
   * `window.triggerRegimenRerender`, wrap it so our recompute runs after it. Nothing in
   * this bundle defines that global, so the wrapper is inert unless something else does.
   */
  const w = window as Window & { triggerRegimenRerender?: () => void };
  const original = w.triggerRegimenRerender;
  if (typeof original === 'function') {
    w.triggerRegimenRerender = () => {
      try {
        original();
      }
      finally {
        recompute();
      }
    };
  }
}
