function numericStatus(target: CoverageTarget, d: Delivery): CoverageStatus {
  const isIU = (target.unit ?? '').toLowerCase() === 'iu';
  const current = isIU ? d.totalIU : d.totalMg;
  const lowRaw = target.low ?? 0;
  const low = isIU ? lowRaw : toMg(lowRaw, target.unit).v;
  if (low <= 0) {
    // Deliberate §00.A rule: no defined floor + nothing delivered ⇒ pending, never a
    // free "covered".
    return current > 0 ? 'covered' : '';
  }
  if (current >= low * 0.95) {
    return 'covered';
  }
  if (current >= low * 0.30) {
    return 'partial';
  }
  return 'gap';
}

/**
 * The 4 organic building blocks (hydrogen · carbon · nitrogen · oxygen) are present in
 * air/water/food by default, so a '' (no-dose) status reads covered, not absent.
 *
 * This rule belongs in the STATE layer, not in a view. When it lived only inside
 * views/knowledge.ts's dot mapper, the drawer painted H/C/N/O green while Coverage
 * rendered the same four tiles blank — two surfaces disagreeing about 4 essentials over
 * ONE snapshot. A coverage verdict is a state decision, never a view decision; both
 * surfaces inherit it from the snapshot. Keyed by canon slug (not the display symbol) so
 * it joins the same way every other target does.
 */
const FOUNDATIONAL_PRESENT_SLUGS: ReadonlySet<string> = new Set([
  'hydrogen',
  'carbon',
  'nitrogen',
  'oxygen',
]);

/**
 * Canon slug -> the display name the layout uses ('' when unknown). Views need this to name
 * an essential they only hold a slug for (a dose card's applies_to, a mirror's CTA) without
 * hand-mapping slugs to names in the view layer — one source per fact.
 */
export function essentialNameOf(slug: string): string {
  return readTargets().find(e => e.slug === slug)?.name ?? '';
}

/**
 * The inverse: a layout key (the canon NAME a tile carries) back to its slug, or null.
 *
 * Several entity-page renderers — the omega family blocks, the non-essential glance — are handed
 * only the layout key, so anything keyed by slug was simply unreachable from them. That was
 * harmless while nothing needed it and stopped being harmless the moment the FOOD SOURCES block
 * did: omega-3 renders through one of those paths, and it has real food sources.
 */
/**
 * The SHORT display name for an essential -- the canon name with its scientific parenthetical and
 * its "/ ..." alternative removed. "Vitamin B1 (Thiamine)" -> "Vitamin B1".
 *
 * A picker listing ninety of these is as wide as its longest entry, and the parentheticals were
 * doubling that width for no gain: a reader choosing a nutrient from a list knows which vitamin
 * they mean (owner, 2026-08-24: "Shorten the Nutrients box by removing the scientific names").
 * The scientific name is still on the essential's own page, where it is the point.
 *
 * DERIVED by the same two rules eden/tools/foods_composition_derive.py uses for the food card's
 * chips, so the two surfaces cannot end up calling the same essential different things. Every
 * parenthetical is dropped rather than only the first, because "Vitamin D2 (Ergocalciferol) + D3
 * (Cholecalciferol)" has to come out as "Vitamin D2 + D3" -- splitting at the first would quietly
 * narrow what the label covers.
 */
export function shortEssentialLabel(slug: string): string {
  const name = essentialNameOf(slug);
  if (name === '') {
    return slug;
  }
  const noParens = name.replace(/\s*\([^)]*\)/g, '');
  return noParens.split(' / ')[0]!.replace(/\s+/g, ' ').trim();
}

export function essentialSlugFor(layoutKey: string): string | null {
  return readTargets().find(e => e.name === layoutKey)?.slug ?? null;
}

/**
 * The stated SAFE INTAKE for an essential Wallach gives no requirement for — or null.
 *
 * Silver is the only case today. The page needs it because the alternative reads as a lie:
 * with no numeric target the glance falls through to "Wallach never states an exact number",
 * and he DOES state one — 400 mcg — just as what you can take, not what you need.
 * Returned from state (not read raw in the view) so the view holds no canonical number.
 */
export function essentialCeiling(slug: string): { amount: number; unit: string } | null {
  const entry = readTargets().find(e => e.slug === slug);
  if (entry === undefined) {
    return null;
  }
  const parsed = CoverageTargetSchema.safeParse(entry.target);
  if (!parsed.success || typeof parsed.data.ceiling !== 'number') {
    return null;
  }
  return { amount: parsed.data.ceiling, unit: parsed.data.unit ?? '' };
}

/** Verdict strength, worst to best. Two INDEPENDENT routes to the same essential are
 *  reconciled by taking the better one — never by summing them, which would double-count
 *  a user who has both. '' (no verdict) must stay the floor so an unscored tile can only
 *  ever be lifted, not dimmed. */
const STATUS_RANK: Record<string, number> = { '': 0, gap: 1, present: 2, partial: 3, trace: 4, covered: 5 };

function betterStatus(a: CoverageStatus, b: CoverageStatus): CoverageStatus {
  return (STATUS_RANK[a] ?? 0) >= (STATUS_RANK[b] ?? 0) ? a : b;
}

function classify(
  target: CoverageTarget | null,
  d: Delivery,
  pdmStatus: CoverageStatus,
  efaStatus: CoverageStatus,
): CoverageStatus {
  const hasSrc = d.sources.length > 0;
  const kind = target?.kind;
  if (target === null || kind === undefined || kind === 'unspecified') {
    return hasSrc ? 'covered' : '';
  }
  if (kind === 'mirrors') {
    // A mirror has NO verdict of its own, ever. Its real status is written by the mirrors
    // pass in buildTiles() once the essential it mirrors has been classified.
    //
    // ★ RETURNING '' HERE IS THE SAFETY PROPERTY, not an oversight. If that pass is removed,
    // reordered, or throws, the tile goes STATUSLESS — never falsely green. It also means a
    // product listing "Cobalt 2 mcg" moves this tile by ZERO, which is the §00.A point:
    // Wallach states no elemental cobalt amount, so there is nothing to measure it against.
    // Note a mirrors target carries no `low`, so it cannot reach numericStatus' `low <= 0 ⇒
    // covered on any delivery` branch either. Two independent reasons it cannot fail green.
    return '';
  }
  if (kind === 'dietary') {
    return hasSrc ? 'covered' : '';
  }
  if (kind === 'trace_pdm') {
    // The 34 trace_pdm minerals share ONE verdict from the plant-derived-mineral
    // aggregate (Σ vehicle mg / goal), computed once per recompute — not per mineral
    // (no product label itemizes them individually). silver/tin carry their own Wallach
    // dose → kind 'wallach' → the numeric path below, never here.
    // ★ DO NOT ROUTE COBALT INTO THIS BRANCH. Its supposed "own Wallach dose" was a B12
    // dose misread as elemental cobalt; with that deleted, the canon's fallback would drop
    // it here — where the meter would render it COVERED off a plant-derived bottle carrying
    // zero B12, while the B12 tile beside it read GAP. It is kind 'mirrors', and never
    // reaches here.
    // NOT "the rare earths": 19 of the 34 are not, by Wallach's own tagging. The group
    // is defined by having no individual dose — see pdm_coverage_derive.py's docstring.
    //
    // ── CHANNEL 2: the presence floor ──────────────────────────────────────────
    // A scanned/manual item can name ONE of the 34 with an exact amount ("Cerium 2 mg").
    // It moves the vehicle meter by ZERO — correctly, because a cerium capsule is not a
    // plant-derived vehicle and Wallach's dose is of the BOTTLE ("Liquid Plant Derived
    // Coloidal Minerals One Ounce/ 100 pounds/day", WAL-CLM-EPIGEN-000089). But the user
    // IS getting cerium, and rendering that tile empty is a lie of omission.
    //
    // The ceiling is 'present' and it can NEVER be 'covered': Wallach states no individual
    // amount for any of the 34, and you cannot be covered against a number that does not
    // exist (§00.A). Only the vehicle meter can promote a tile to covered.
    //
    // It lifts ONLY the empty state. Any real verdict (covered/partial/gap) wins, because
    // that is a measured ratio against Wallach's own dose and it outranks an unmeasurable
    // "you have some". Consistent with pdmStatusOf's ladder, where 'present' is already what
    // a vehicle-in-stack-but-unquantified produces.
    if (pdmStatus === '' && d.sources.length > 0) {
      return 'present';
    }
    return pdmStatus;
  }
  if (kind === 'wallach_collective') {
    // ★ DO NOT MERGE THIS BRANCH BACK INTO trace_pdm. While wallach_collective was a dead
    // alias that no target carried, routing it to the RARE-EARTH mineral meter looked
    // harmless. The moment the derive started emitting it for the omegas, two plant-derived
    // MINERAL products carrying ZERO fatty acids rendered OMEGA-3 and OMEGA-6 as "covered".
    // A dead alias is not inert; it is a loaded branch waiting for someone to feed it.
    // Every collective group MUST route to its own meter, keyed by the group the
    // claim names. No group => no verdict, never a neighbouring group's.
    if (target.collective_group === 'essential-fatty-acids') {
      return efaStatus;
    }
    return '';
  }
  if (kind === 'dietary_with_clinical_lever') {
    if (target.low !== undefined && target.low > 0) {
      return numericStatus(target, d);
    }
    // ★ GERMANIUM'S UNIQUE CASE. An essential can state NO amount and still have the
    // plant-derived vehicle as a real supply route. Without this branch the function
    // returned here and never reached the vehicle_supplied check further down, so a
    // PDM bottle moved the tile by zero — which is what made germanium the only tile in
    // the app unreachable by anything at all.
    //
    // Unlike tin, there is no numeric side to take the better of: the vehicle IS the only
    // measured route. Presence still wins on its own, so a scanned item declaring
    // germanium covers it with no vehicle present, exactly as the amino acids behave.
    if (target.vehicle_supplied === true) {
      return betterStatus(pdmStatus, hasSrc ? 'covered' : '');
    }
    return hasSrc ? 'covered' : '';
  }
  // A target of ZERO is Wallach saying "take none", and it is MET by taking none. You cannot
  // be under 30% of zero, so numericStatus would post 'gap' and tell the user to close a gap
  // he says does not exist. The only such row in his base-line program is PHOSPHORUS: FIG. 8-1
  // reads `PHOSPHORUS 800 mg 0.0 0.0` — RDA 800 | True Supplement Need 0.0 | pharmacologic 0.0
  // (lets-play-doctor:3775 → WAL-CLM-LETS-000061). ★ The 800 is the RDA COLUMN — the number
  // Wallach argues against, NOT a second Wallach amount. Proven by the four rows carrying '?'
  // in that column and by the two rows where his own figure sits BELOW it (vitamin D 275 vs
  // 400; phosphorus 0 vs 800). Never surface the 800 as a target (§00.A).
  // This is why phosphorus renders in FOUNDATIONAL and is NOT in FOUNDATIONAL_PRESENT_SLUGS:
  // its 'covered' traces to a sealed Wallach claim, not to the present-by-default rule.
  if (target.low === 0) {
    return 'covered';
  }
  // ── VEHICLE-SUPPLIED ────────────────────────────────────────────────────────────
  // Wallach names the plant-derived colloidal vehicle as THIS essential's supply route,
  // in his own words (tin: "tin from plant derived colloidal minerals", two books 16 years
  // apart, plus his own use of it). So a vehicle in the stack is a real Wallach-stated
  // route to it, not an inference from the humic-shale roster — which lists calcium and
  // therefore cannot be the test. Membership + citations live in trace-mineral-vehicles.json.
  //
  // ADDITIVE, never a replacement: the numeric path still runs and the BETTER verdict wins,
  // so a declared item meeting the 500 mcg still covers with no vehicle present, and a
  // vehicle still covers with nothing declared. Removing either side is a behaviour change.
  if (target.vehicle_supplied === true) {
    return betterStatus(pdmStatus, numericStatus(target, d));
  }
  // Numeric: hbsp · wallach · wallach_clinical · any kind carrying low/unit.
  return numericStatus(target, d);
}

function deliveryRatio(target: CoverageTarget | null, status: CoverageStatus, d: Delivery): number {
  if (target === null) {
    return status === 'covered' || status === 'trace' ? 1 : 0;
  }
  const isIU = (target.unit ?? '').toLowerCase() === 'iu';
  const current = isIU ? d.totalIU : d.totalMg;
  const lowRaw = target.low ?? 0;
  const low = isIU ? lowRaw : toMg(lowRaw, target.unit).v;
  if (low > 0) {
    return current / low;
  }
  return status === 'covered' || status === 'trace' ? 1 : 0;
}

